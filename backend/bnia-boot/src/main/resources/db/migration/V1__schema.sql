    siege_code_pays      text,
    facturation_ligne1       text,
    facturation_ligne2       text,
    facturation_code_postal  text,
    facturation_ville        text,
    facturation_pays         text,
    facturation_code_pays    text,
    siren                text      not null,
    siret                text      not null,
    numero_tva           text      not null,
    iban                 text      not null,
    bic                  text      not null,
    telephone            text      not null,
    email                text      not null,
    tva_sur_debits       boolean   not null,
    escompte             text      not null,
    penalites            text      not null
);

-- Compteur des numéros par année (A-FAC-5), commun aux factures et aux avoirs (H-FAC-4) : lu FOR UPDATE dans la
-- transaction d'émission, un rollback ne consomme pas le numéro (RG-FAC-12).
create table facturation.numerotation (
    annee    integer  primary key,
    dernier  bigint   not null check (dernier between 0 and 999999)
);

-- Agrégat Facture (spec 08 §3.1) : facture ou avoir, brouillon puis émise. L'acheteur est recopié (§3.5) ; le
-- vendeur l'est à l'émission (§3.7). Les totaux sont ceux du domaine (RG-FAC-05), stockés pour l'historique.
create table facturation.facture (
    id                              bigint       generated by default as identity primary key,
    sens                            text         not null check (sens in ('FACTURE', 'AVOIR')),
    etat                            text         not null check (etat in ('BROUILLON', 'EMISE')),
    origine_source                  text,
    origine_nature                  text,
    origine_libelle_nature          text,
    origine_identifiant             text,
    origine_reference               text,
    date_operation                  date         not null,
    libelle_periode                 text,
    condition_jours                 integer      not null check (condition_jours between 0 and 60),
    condition_fin_de_mois           boolean      not null,
    bon_de_commande                 text,
    note_entete                     text,
    note_pied                       text,
    acheteur_client_identifiant     text,
    acheteur_client_code            text,
    acheteur_categorie              text         not null check (acheteur_categorie in ('PROFESSIONNEL', 'PARTICULIER')),
    acheteur_nom                    text,
    acheteur_siren                  text,
    acheteur_siret                  text,
    acheteur_numero_tva             text,
    acheteur_facturation_ligne1     text,
    acheteur_facturation_ligne2     text,
    acheteur_facturation_code_postal text,
    acheteur_facturation_ville      text,
    acheteur_facturation_pays       text,
    acheteur_facturation_code_pays  text,
    acheteur_livraison_ligne1       text,
    acheteur_livraison_ligne2       text,
    acheteur_livraison_code_postal  text,
    acheteur_livraison_ville        text,
    acheteur_livraison_pays         text,
    acheteur_livraison_code_pays    text,
    acheteur_email                  text,
    vendeur_nom                     text,
    vendeur_siege_ligne1            text,
    vendeur_siege_ligne2            text,
    vendeur_siege_code_postal       text,
    vendeur_siege_ville             text,
    vendeur_siege_pays              text,
    vendeur_siege_code_pays         text,
    vendeur_facturation_ligne1      text,
    vendeur_facturation_ligne2      text,
    vendeur_facturation_code_postal text,
    vendeur_facturation_ville       text,
    vendeur_facturation_pays        text,
    vendeur_facturation_code_pays   text,
    vendeur_siren                   text,
    vendeur_siret                   text,
    vendeur_numero_tva              text,
    vendeur_iban                    text,
    vendeur_bic                     text,
    vendeur_telephone               text,
    vendeur_email                   text,
    vendeur_tva_sur_debits          boolean,
    vendeur_escompte                text,
    vendeur_penalites               text,
    numero                          text         unique,
    date_emission                   date,
    echeance                        date,
    pdf_document_id                 bigint       unique references documents.document (id),
    pdf_nom                         text,
    pdf_taille                      bigint,
    total_ht                        numeric(14,2) not null,
    total_tva                       numeric(14,2) not null,
    total_ttc                       numeric(14,2) not null,
    creee_le                        timestamptz  not null,
    creee_par_id                    bigint       not null,
    nom_creee_par                   text         not null,
    version                         bigint       not null,
    -- Une facture a une origine (complète), un avoir n'en a pas (§3.1).
    check ((sens = 'FACTURE') = (origine_source is not null)),
    check (origine_source is null or (origine_nature is not null and origine_libelle_nature is not null
        and origine_identifiant is not null and origine_reference is not null)),
    -- RG-FAC-09, 12, 15 : une pièce émise a son numéro, ses dates, son vendeur et son PDF ; un brouillon, aucun.
    check ((etat = 'EMISE') = (numero is not null)),
    check (etat = 'BROUILLON' or (date_emission is not null and echeance is not null and vendeur_nom is not null
        and pdf_document_id is not null)),
    check (etat = 'EMISE' or (date_emission is null and vendeur_nom is null and pdf_document_id is null)),
    check (numero is null or numero ~ '^[0-9]{10}$'),
    check (total_ttc >= 0 or etat = 'BROUILLON')
);
-- RG-FAC-02 : une origine n'a qu'une facture vivante (A-FAC-8 ; l'annulation libérera l'origine au lot 4).
create unique index facture_origine_vivante on facturation.facture (origine_source, origine_identifiant)
    where sens = 'FACTURE';
-- Historique par client (RG-FAC-27), puis portail (RG-FAC-28).
create index facture_client on facturation.facture (acheteur_client_identifiant);
create index facture_date_emission on facturation.facture (date_emission desc);

-- Lignes de la pièce (A-FAC-4) : une table, sorte ARTICLE, TEXTE ou GROUPE ; position = ordre d'impression. Une
-- ligne d'un groupe désigne la position de sa ligne GROUPE dans la même pièce (un seul niveau, RG-FAC-04). texte :
-- désignation d'un article, texte informatif ou titre d'un groupe. numero : identité stable de la ligne dans la
-- pièce, qui survit aux déplacements ; recue : ligne reçue de la source avec la demande, verrouillée (RG-FAC-17).
create table facturation.ligne_facture (
    facture_id      bigint         not null references facturation.facture (id) on delete cascade,
    position        integer        not null,
    numero          integer        not null check (numero > 0),
    recue           boolean        not null,
    sorte           text           not null check (sorte in ('ARTICLE', 'TEXTE', 'GROUPE')),
    groupe          integer,
    texte           text           not null,
    article_source  text,
    article_code    text,
    unite           text,
    nature          text           check (nature in ('BIEN', 'SERVICE')),
    code_comptable  text,
    quantite        numeric(14,4)  check (quantite <> 0),
    prix_unitaire   numeric(14,4),
    tva_code        text           check (tva_code in ('S', 'Z', 'E', 'O')),
    tva_taux        numeric(5,2),
    tva_motif       text,
    montant_ht      numeric(14,2),
    primary key (facture_id, position),
    unique (facture_id, numero),
    foreign key (facture_id, groupe) references facturation.ligne_facture (facture_id, position)
        deferrable initially deferred,
    check ((sorte = 'ARTICLE') = (article_code is not null)),
    check (sorte <> 'ARTICLE' or (article_source is not null and nature is not null and quantite is not null
        and prix_unitaire is not null and tva_code is not null and montant_ht is not null)),
    check (sorte <> 'GROUPE' or groupe is null)
);

-- Journal des pièces (spec 08 §3.9, RG-FAC-20) : en ajout seul, supprimé avec un brouillon abandonné (lot 2).
-- L'acteur est copié, sans clé étrangère (ADR-011 amendé) : utilisateur_id vide pour un traitement.
create table facturation.journal (
    id              bigint       generated by default as identity primary key,
    facture_id      bigint       not null references facturation.facture (id) on delete cascade,
    date            timestamptz  not null,
    evenement       text         not null check (evenement in ('DEMANDEE', 'CREEE', 'MODIFIEE', 'EMISE', 'CONSULTEE',
                        'ANNULEE', 'AVOIR_EMIS', 'DEPOSEE', 'REJETEE', 'EN_ANOMALIE', 'PAYEE', 'NOTE')),
    utilisateur_id  bigint,
    nom_acteur      text         not null,
    cote            text         not null check (cote in ('VENDEUR', 'CLIENT')),
    detail          text
);
create index journal_facturation_facture on facturation.journal (facture_id, date desc, id desc);
