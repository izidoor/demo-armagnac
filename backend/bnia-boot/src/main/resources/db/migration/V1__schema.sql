);

-- Médailles et concours, semi-structurés (RG-OPE-19).
create table operateurs.medaille_concours (
    presentation_id bigint  not null references operateurs.presentation_operateur (id) on delete cascade,
    rang            integer not null,
    concours        text    not null,
    annee           integer check (annee between 1800 and 2100),
    distinction     text    check (distinction in ('OR', 'ARGENT', 'BRONZE', 'AUTRE')),
    produit         text,
    primary key (presentation_id, rang)
);

-- =====================================================================================================
-- 3. authentification (spec 03) : preuve d'identité, sans métier (ADR-015). Ni nom, ni droit, ni
--    opérateur. Le compte référence l'utilisateur de operateurs sans clé étrangère : aucune clé ne
--    traverse les deux schémas ; il est créé, renommé et supprimé par les événements de operateurs.
-- =====================================================================================================

-- Agrégat CompteConnexion (§3.1) : identifiant de connexion = e-mail de l'utilisateur (RG-AUT-10),
-- mot de passe haché, vide entre l'acceptation d'une invitation et le premier mot de passe (RG-AUT-15).
