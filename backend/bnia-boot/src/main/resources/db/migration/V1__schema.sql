-- =====================================================================================================
-- 3. authentification (spec 03) : preuve d'identité, sans métier (ADR-015). Ni nom, ni droit, ni
--    opérateur. Le compte référence l'utilisateur de operateurs sans clé étrangère : aucune clé ne
--    traverse les deux schémas ; il est créé, renommé et supprimé par les événements de operateurs.
-- =====================================================================================================

-- Agrégat CompteConnexion (§3.1) : identifiant de connexion = e-mail de l'utilisateur (RG-AUT-10),
-- mot de passe haché, vide entre l'acceptation d'une invitation et le premier mot de passe (RG-AUT-15).
create table authentification.compte (
    id                      bigint       generated by default as identity primary key,
    utilisateur_id          bigint       not null unique,
    identifiant             text         not null,
    mot_de_passe            text,
    echecs                  integer      not null default 0 check (echecs >= 0),
    bloque_jusqua           timestamptz,
    derniere_connexion      timestamptz,
    mot_de_passe_change_le  timestamptz
);
create unique index compte_identifiant_unique on authentification.compte (lower(identifiant));

-- Code de vérification en cours (RG-AUT-05) : un au plus, en empreinte.
create table authentification.code_verification (
    compte_id  bigint       primary key references authentification.compte (id) on delete cascade,
    empreinte  text         not null,
    expire_le  timestamptz  not null
);

-- Réinitialisation du mot de passe en cours (RG-AUT-08) : une au plus, jeton en empreinte.
create table authentification.reinitialisation (
    compte_id  bigint       primary key references authentification.compte (id) on delete cascade,
    empreinte  text         not null unique,
    expire_le  timestamptz  not null
);

-- Navigateurs de confiance (RG-AUT-06) : jeton du cookie en empreinte.
create table authentification.navigateur_confiance (
    compte_id  bigint       not null references authentification.compte (id) on delete cascade,
    empreinte  text         not null unique,
    cree_le    timestamptz  not null,
    expire_le  timestamptz  not null,
    primary key (compte_id, empreinte)
);

-- Journal des connexions (RG-AUT-12), hors agrégat, en ajout seul : survit à la suppression du compte.
create table authentification.journal_connexion (
    id                 bigint       generated by default as identity primary key,
    date               timestamptz  not null,
    identifiant_saisi  text         not null,
    utilisateur_id     bigint,
    evenement          text         not null check (evenement in ('CONNEXION_REUSSIE', 'ECHEC_MOT_DE_PASSE',
                           'ECHEC_CODE', 'BLOCAGE_DECLENCHE', 'CONNEXION_REFUSEE', 'DECONNEXION', 'MOT_DE_PASSE_DEFINI',
                           'MOT_DE_PASSE_CHANGE', 'REINITIALISATION_DEMANDEE', 'MOT_DE_PASSE_REINITIALISE',
                           'NAVIGATEUR_DE_CONFIANCE')),
    detail             text,
    adresse_ip         text,
    navigateur         text
);
create index journal_connexion_date on authentification.journal_connexion (date desc);
create index journal_connexion_utilisateur on authentification.journal_connexion (utilisateur_id, date desc);

-- Sessions serveur (A-AUT-3) : tables de Spring Session JDBC (schéma fourni pour PostgreSQL), dans ce
-- schéma (spring.session.jdbc.table-name). La session ne porte que l'identifiant de l'utilisateur.
create table authentification.spring_session (
    primary_id            char(36)      not null primary key,
    session_id            char(36)      not null,
    creation_time         bigint        not null,
    last_access_time      bigint        not null,
    max_inactive_interval int           not null,
    expiry_time           bigint        not null,
    principal_name        varchar(100)
);
create unique index spring_session_ix1 on authentification.spring_session (session_id);
create index spring_session_ix2 on authentification.spring_session (expiry_time);
create index spring_session_ix3 on authentification.spring_session (principal_name);

create table authentification.spring_session_attributes (
    session_primary_id char(36)     not null references authentification.spring_session (primary_id) on delete cascade,
    attribute_name     varchar(200) not null,
    attribute_bytes    bytea        not null,
    primary key (session_primary_id, attribute_name)
);
