-- =====================================================================================================
-- 1. referentiels (spec 01) : données de référence administrées par le BNIA.
--    Référencées par leur identifiant technique depuis les autres contextes (ADR-011) ; le code se
--    corrige et reste unique dans sa liste, sans distinction de casse (RG-REF-01, 02). Une valeur
--    utilisée ailleurs ne se supprime pas (clé étrangère) : elle se désactive (RG-REF-04).
-- =====================================================================================================

-- Géographie (C.10.4 à C.10.6)
create table referentiels.zone_commerciale (
    id      bigint  generated by default as identity primary key,
    code    text    not null,
    libelle text    not null,
    actif   boolean not null default true
);
create unique index zone_commerciale_code_unique on referentiels.zone_commerciale (lower(code));

-- Code ISO 3166-1 alpha-2 unique (RG-REF-06). Âge minimum : compte d'âge sous forme canonique
-- ('00', '0', '4'…), ce n'est pas un entier (RG-REF-09).
create table referentiels.pays (
    id                       bigint  generated by default as identity primary key,
    code                     text    not null,
    code_iso                 text    not null unique check (code_iso ~ '^[A-Z]{2}$'),
    libelle                  text    not null,
    zone_commerciale_id      bigint  not null references referentiels.zone_commerciale (id),
    membre_ue                boolean not null default false,
    langue_certificat        text    not null default 'FR_EN'
                                     check (langue_certificat in ('FR_EN', 'FR_ES', 'FR_IT')),
    niveau_detail_certificat text    not null default 'CUMUL_DEGRE'
                                     check (niveau_detail_certificat in ('CUMUL_DEGRE', 'DETAIL_COMPTE_AGE', 'DETAIL_MILLESIME')),
    age_minimum              text    check (age_minimum ~ '^(00|0|[1-9][0-9]{0,2})$'),
    actif                    boolean not null default true
);
create unique index pays_code_unique on referentiels.pays (lower(code));

create table referentiels.region (
    id      bigint  generated by default as identity primary key,
    code    text    not null,
    libelle text    not null,
    en_region_delimitee boolean not null,
    actif   boolean not null default true
);
create unique index region_code_unique on referentiels.region (lower(code));

-- Qualification (C.10.8)
create table referentiels.titre (
    id      bigint  generated by default as identity primary key,
    code    text    not null,
    libelle text    not null,
    actif   boolean not null default true
);
create unique index titre_code_unique on referentiels.titre (lower(code));

create table referentiels.label (
    id      bigint  generated by default as identity primary key,
    code    text    not null,
    libelle text    not null,
    actif   boolean not null default true
);
create unique index label_code_unique on referentiels.label (lower(code));

create table referentiels.type_visite (
    id      bigint  generated by default as identity primary key,
    code    text    not null,
    libelle text    not null,
    actif   boolean not null default true
);
create unique index type_visite_code_unique on referentiels.type_visite (lower(code));

create table referentiels.langue (
    id      bigint  generated by default as identity primary key,
    code    text    not null,
    libelle text    not null,
    actif   boolean not null default true
);
create unique index langue_code_unique on referentiels.langue (lower(code));

create table referentiels.centre_interet (
    id      bigint  generated by default as identity primary key,
    code    text    not null,
    libelle text    not null,
    actif   boolean not null default true
);
create unique index centre_interet_code_unique on referentiels.centre_interet (lower(code));

-- Membre BNIA de la fiche opérateur (C.1.1.1 p.101) ; liste ajoutée par la spec 02 (Q-OPE-4).
create table referentiels.membre_bnia (
    id      bigint  generated by default as identity primary key,
    code    text    not null,
    libelle text    not null,
    actif   boolean not null default true
);
create unique index membre_bnia_code_unique on referentiels.membre_bnia (lower(code));

-- Présentation et commercialisation (C.10.9)
create table referentiels.circuit_distribution (
    id      bigint  generated by default as identity primary key,
    code    text    not null,
    libelle text    not null,
    actif   boolean not null default true
);
create unique index circuit_distribution_code_unique on referentiels.circuit_distribution (lower(code));

create table referentiels.produit_commercialise (
    id      bigint  generated by default as identity primary key,
    code    text    not null,
    libelle text    not null,
    actif   boolean not null default true
);
create unique index produit_commercialise_code_unique on referentiels.produit_commercialise (lower(code));

-- Contenance : un volume en litres, unique (RG-REF-10). Libellé facultatif.
create table referentiels.contenance (
    id      bigint         generated by default as identity primary key,
    volume  numeric(10, 3) not null unique check (volume > 0),
    libelle text,
    actif   boolean        not null default true
);

-- Libellé unique à la casse, aux accents et aux espaces près, inactives comprises (RG-REF-15).
create table referentiels.marque (
    id                bigint  generated by default as identity primary key,
    code              text    not null,
    libelle           text    not null,
    libelle_normalise text    not null unique,
    actif             boolean not null default true
);
create unique index marque_code_unique on referentiels.marque (lower(code));

-- Fiscalité (C.10.1-2) : une classe de TVA et l'historique de ses taux (agrégat). Le non-chevauchement
-- des périodes est garanti par l'agrégat (RG-REF-11) ; la base garantit qu'un début n'est pas répété.
-- Supprimer une classe supprime ses taux (ils font partie de l'agrégat).
create table referentiels.classe_tva (
    id      bigint  generated by default as identity primary key,
    code    text    not null,
    libelle text    not null,
    actif   boolean not null default true
);
create unique index classe_tva_code_unique on referentiels.classe_tva (lower(code));

create table referentiels.taux_tva (
    classe_tva_id bigint        not null references referentiels.classe_tva (id) on delete cascade,
    taux          numeric(5, 2) not null check (taux between 0 and 100),
    date_debut    date          not null,
    date_fin      date          check (date_fin >= date_debut),
    primary key (classe_tva_id, date_debut)
);

-- =====================================================================================================
-- 2. operateurs (spec 02) : structures suivies par le BNIA, le BNIA lui-même, leurs personnes et leurs
--    accès (ADR-012, ADR-016). Référencés par leur identifiant technique depuis les autres contextes
--    (ADR-011). Le code est unique sans distinction de casse et se corrige (RG-OPE-04) ; un opérateur
--    utilisé ailleurs ne se supprime pas (clé étrangère) : il se désactive (RG-OPE-25).
-- =====================================================================================================

-- Agrégat Operateur. Formes normalisées (casse, accents, espaces) stockées pour les doublons de raison
-- sociale (RG-OPE-08) et le regroupement (RG-OPE-09). CVI, SIRET et accise stockés sous forme compacte,
-- en majuscules (RG-OPE-06). Un seul opérateur de type BNIA (RG-OPE-39), inséré plus bas.
create table operateurs.operateur (
    id                        bigint        generated by default as identity primary key,
    type                      text          not null check (type in ('BNIA', 'PRODUCTEUR', 'NEGOCIANT', 'AUTRE')),
    code                      text          not null,
    groupe                    text,
    groupe_normalise          text,
    cvi                       text          check (cvi ~ '^[A-Z0-9]{10}$'),
    siret                     text          check (siret ~ '^[0-9]{14}$'),
    numero_tva                text          check (numero_tva ~ '^FR[0-9]{11}$'),
    accise                    text          check (accise ~ '^FR[A-Z0-9]{11}$'),
    bureau_douanes            text,
    identifiant_odg           text,
    titre_id                  bigint        references referentiels.titre (id),
    raison_sociale            text          not null,
    raison_sociale_normalisee text          not null,
    nom_commercial            text,
    adresse_ligne1            text,
    adresse_ligne2            text,
    adresse_ligne3            text,
    code_postal               text,
    ville                     text,
    pays_id                   bigint        references referentiels.pays (id),
    telephone1                text,
    telephone2                text,
    portable                  text,
    email_general             text,
    site_web                  text,
    site_commercial           text,
    latitude                  numeric(9, 6) check (latitude between -90 and 90),
    longitude                 numeric(9, 6) check (longitude between -180 and 180),
    membre_bnia_id            bigint        references referentiels.membre_bnia (id),
    accord_diffusion_general  boolean       not null default false,
    commentaire_interne       text,
    -- Déclaratif (RG-OPE-01, 10, 11) : pas de périodicité pour AUTRE et BNIA, obligatoire sinon.
    periodicite_dsm           text          check (periodicite_dsm in ('MENSUELLE', 'TRIMESTRIELLE', 'SEMESTRIELLE', 'ANNUELLE')),
    statut_declaration_stock  text          not null check (statut_declaration_stock in ('OUI', 'NON', 'SOMMEIL', 'CLOTURE')),
    region_id                 bigint        references referentiels.region (id),
    -- Diffusion des millésimes (RG-OPE-14) et accès aux statistiques du portail (RG-OPE-15).
    niveau_diffusion          text          not null default 'REFUS' check (niveau_diffusion in ('REFUS', 'PARTIEL', 'TOTAL')),
    acces_statistiques        boolean       not null default false,
    actif                     boolean       not null default true,
    -- Désignations (RG-OPE-22, 23) : des fiches professionnelles ; clés étrangères ajoutées après leur table.
    contact_principal_fiche_id        bigint,
    destinataire_factures_fiche_id    bigint,
    destinataire_factures_email       text,
    -- Contrôle de concurrence (RG-OPE-51).
    version                   bigint        not null default 0,
    check (destinataire_factures_fiche_id is null or destinataire_factures_email is null),
    check ((latitude is null) = (longitude is null)),
    check ((type in ('AUTRE', 'BNIA')) = (periodicite_dsm is null)),
    check (type not in ('AUTRE', 'BNIA') or statut_declaration_stock <> 'OUI'),
    check (type <> 'BNIA' or actif)
);
create unique index operateur_code_unique on operateurs.operateur (lower(code));
create unique index operateur_identifiant_odg_unique on operateurs.operateur (lower(identifiant_odg));
create unique index operateur_bnia_unique on operateurs.operateur (type) where type = 'BNIA';
create index operateur_groupe on operateurs.operateur (groupe_normalise);
create index operateur_raison_sociale on operateurs.operateur (raison_sociale_normalisee);

-- L'interprofession (RG-OPE-39) : créée par l'application, jamais par la création d'un opérateur. Ses
-- coordonnées se complètent à l'écran (menu « BNIA »).
insert into operateurs.operateur (type, code, raison_sociale, raison_sociale_normalisee, statut_declaration_stock)
values ('BNIA', 'BNIA', 'Bureau National Interprofessionnel de l''Armagnac',
        'BUREAU NATIONAL INTERPROFESSIONNEL DE L''ARMAGNAC', 'NON');

-- Production (C.1.1.2, C.1.2 p.102) : appellations (RG-OPE-12) et alambics (RG-OPE-13), dans l'agrégat.
create table operateurs.operateur_appellation (
    operateur_id bigint not null references operateurs.operateur (id) on delete cascade,
    appellation  text   not null check (appellation in ('ARMAGNAC', 'BAS_ARMAGNAC', 'ARMAGNAC_TENAREZE', 'HAUT_ARMAGNAC', 'BLANCHE_ARMAGNAC')),
    primary key (operateur_id, appellation)
);

create table operateurs.alambic (
    operateur_id    bigint         not null references operateurs.operateur (id) on delete cascade,
    rang            integer        not null,
    numero_agrement text,
    type            text           not null check (type in ('ARMAGNACAIS', 'DOUBLE_CHAUFFE')),
    capacite        numeric(10, 2) check (capacite > 0),
    primary key (operateur_id, rang)
);

-- Millésimes diffusables, en accord partiel seulement (RG-OPE-14 ; contrôle dans l'agrégat).
create table operateurs.millesime_diffusable (
    operateur_id bigint  not null references operateurs.operateur (id) on delete cascade,
    millesime    integer not null check (millesime between 1800 and 2100),
    primary key (operateur_id, millesime)
);

-- Personnes et accès (spec 02 §3.2, ADR-016) : un agrégat par table racine. Les règles collectives
-- sont dans les cas d'usage, appuyées par les index uniques ci-dessous et par un verrou sur la ligne de
-- l'opérateur (RG-OPE-35). Tout disparaît avec l'opérateur (RG-OPE-25).

-- Agrégat FicheProfessionnelle : propriété de l'opérateur, portée par un contact ou un rattachement
-- (RG-OPE-30), et la même ligne quand la personne change d'état.
create table operateurs.fiche_professionnelle (
    id                       bigint      generated by default as identity primary key,
    operateur_id             bigint      not null references operateurs.operateur (id) on delete cascade,
    type                     text        not null check (type in ('CONTACT', 'RATTACHEMENT')),
    fonction                 text,
    telephone_professionnel  text,
    telephone_secondaire     text,
    adresse                  text,
    code_postal              text,
    ville                    text,
    pays_id                  bigint      references referentiels.pays (id),
    observation              text,
    modifiee_par             text,
    modifiee_le              timestamptz,
    version                  bigint      not null default 0
);
create index fiche_professionnelle_operateur on operateurs.fiche_professionnelle (operateur_id);

create table operateurs.fiche_centre_interet (
    fiche_id           bigint not null references operateurs.fiche_professionnelle (id) on delete cascade,
    centre_interet_id  bigint not null references referentiels.centre_interet (id),
    primary key (fiche_id, centre_interet_id)
);

-- RG-OPE-22, 23 : une désignation tombe avec sa fiche.
alter table operateurs.operateur
    add foreign key (contact_principal_fiche_id) references operateurs.fiche_professionnelle (id) on delete set null,
    add foreign key (destinataire_factures_fiche_id) references operateurs.fiche_professionnelle (id) on delete set null;

-- Agrégat Contact : personne sans compte, identité propriété de l'opérateur. E-mail unique parmi les
-- contacts de l'opérateur (RG-OPE-28) ; une fiche, à lui seul (RG-OPE-30).
create table operateurs.contact (
    id            bigint  generated by default as identity primary key,
    operateur_id  bigint  not null references operateurs.operateur (id) on delete cascade,
    titre_id      bigint  references referentiels.titre (id),
    nom           text    not null,
    prenom        text,
    email         text,
    fiche_id      bigint  not null unique references operateurs.fiche_professionnelle (id),
    version       bigint  not null default 0
);
create unique index contact_email_unique on operateurs.contact (operateur_id, lower(email));

-- Agrégat Utilisateur : personne avec un compte, propriétaire de son identité. Un e-mail, un utilisateur
-- (RG-OPE-29). Son compte de connexion est dans authentification, sans clé étrangère (ADR-015).
create table operateurs.utilisateur (
    id                  bigint  generated by default as identity primary key,
    titre_id            bigint  references referentiels.titre (id),
    nom                 text    not null,
    prenom              text    not null,
    email               text    not null,
    statut              text    not null default 'ACTIF' check (statut in ('ACTIF', 'BLOQUE')),
    operateur_actif_id  bigint  references operateurs.operateur (id) on delete set null,
    version             bigint  not null default 0
);
create unique index utilisateur_email_unique on operateurs.utilisateur (lower(email));

-- Demande de changement d'e-mail en cours (RG-OPE-48), une au plus, dans l'agrégat Utilisateur.
create table operateurs.changement_email (
    utilisateur_id  bigint       primary key references operateurs.utilisateur (id) on delete cascade,
    nouvel_email    text         not null,
    empreinte       text         not null unique,
    expire_le       timestamptz  not null
);

-- Agrégat Rattachement : un par opérateur et utilisateur (RG-OPE-29), avec sa fiche (RG-OPE-30).
create table operateurs.rattachement (
    id              bigint       generated by default as identity primary key,
    operateur_id    bigint       not null references operateurs.operateur (id) on delete cascade,
    utilisateur_id  bigint       not null references operateurs.utilisateur (id),
    role            text         not null check (role in ('OBSERVATEUR', 'AGENT', 'ADMIN')),
    statut          text         not null default 'ACTIF' check (statut in ('ACTIF', 'SUSPENDU')),
    fiche_id        bigint       not null unique references operateurs.fiche_professionnelle (id),
    cree_le         timestamptz  not null,
    unique (operateur_id, utilisateur_id)
);
create index rattachement_utilisateur on operateurs.rattachement (utilisateur_id);

-- Agrégat Invitation (RG-OPE-40 à 42) : jeton conservé en empreinte ; une en attente par e-mail et
-- opérateur (index partiel). Part d'un contact (sa fiche) ou d'une personne nouvelle (identité copiée).
create table operateurs.invitation (
    id                       bigint       generated by default as identity primary key,
    operateur_id             bigint       not null references operateurs.operateur (id) on delete cascade,
    email                    text         not null,
    role                     text         not null check (role in ('OBSERVATEUR', 'AGENT', 'ADMIN')),
    statut                   text         not null check (statut in ('EN_ATTENTE', 'ACCEPTEE', 'ANNULEE', 'EXPIREE')),
    expire_le                timestamptz  not null,
    empreinte                text         not null unique,
    fiche_id                 bigint       references operateurs.fiche_professionnelle (id) on delete set null,
    titre_id                 bigint       references referentiels.titre (id),
    nom                      text,
    prenom                   text,
    fonction                 text,
    telephone_professionnel  text,
    envoyee_par              text         not null,
    envoyee_le               timestamptz  not null,
    acceptee_le              timestamptz,
    utilisateur_id           bigint       references operateurs.utilisateur (id) on delete set null,
    -- RG-OPE-42 : le compte qui avait cet e-mail à l'envoi ; s'il en a changé, l'invitation ne s'accepte plus.
    compte_vise_id           bigint       references operateurs.utilisateur (id) on delete set null
);
create unique index invitation_en_attente_unique on operateurs.invitation (operateur_id, lower(email))
    where statut = 'EN_ATTENTE';
create index invitation_fiche on operateurs.invitation (fiche_id);

-- Journal des personnes et des accès (RG-OPE-34), hors agrégat, en ajout seul. Acteur et cible copiés,
-- sans clé étrangère : il survit à leur suppression (A-OPE-8). Vide pour une action sur un utilisateur.
create table operateurs.journal (
    id            bigint       generated by default as identity primary key,
    date          timestamptz  not null,
    acteur_id     bigint,
    nom_acteur    text         not null,
    operateur_id  bigint       references operateurs.operateur (id) on delete cascade,
    action        text         not null check (action in ('CONTACT_CREE', 'CONTACT_MODIFIE', 'CONTACT_SUPPRIME',
                      'FICHE_MODIFIEE', 'INVITATION_ENVOYEE', 'INVITATION_RELANCEE', 'INVITATION_ANNULEE',
                      'INVITATION_EXPIREE', 'INVITATION_ACCEPTEE', 'ROLE_CHANGE', 'ACCES_SUSPENDU', 'ACCES_REACTIVE',
                      'ACCES_RETIRE', 'PROFIL_MODIFIE', 'EMAIL_MODIFIE', 'UTILISATEUR_BLOQUE', 'UTILISATEUR_DEBLOQUE',
                      'UTILISATEUR_SUPPRIME')),
    cible         text         not null check (cible in ('CONTACT', 'MEMBRE', 'INVITATION', 'UTILISATEUR')),
    id_cible      bigint       not null,
    nom_cible     text         not null
);
create index journal_operateur on operateurs.journal (operateur_id, date desc);
create index journal_cible on operateurs.journal (cible, id_cible);

create table operateurs.journal_changement (
    journal_id bigint  not null references operateurs.journal (id) on delete cascade,
    rang       integer not null,
    champ      text    not null,
    avant      text,
    apres      text,
    primary key (journal_id, rang)
);

-- Agrégat PresentationOperateur (C.1.4 à C.1.7 p.103-104, ADR-012) : même identifiant que l'opérateur,
