-- 5. declarations (spec 05) : déclarations de stocks et mouvements (DSM), point de départ déclaratif,
--    journal. L'opérateur est référencé par son identifiant, avec clé étrangère (ADR-011) : un opérateur
--    qui a déclaré ne se supprime pas, il se désactive (RG-OPE-25). L'auteur d'une action : identifiant
--    sans clé étrangère et copie de son nom (ADR-011 amendé).
-- =====================================================================================================

-- Agrégat PointDeDepartDeclaratif (spec 05 §3.3) : le plus récent est en vigueur. Début et règles des
-- lignes contrôlés par l'agrégat (RG-DEC-06, 07) ; un début par opérateur.
create table declarations.point_de_depart (
    id            bigint       generated by default as identity primary key,
    operateur_id  bigint       not null references operateurs.operateur (id),
    debut         date         not null,
    fixe_par_id   bigint       not null,
    nom_fixe_par  text         not null,
    fixe_le       timestamptz  not null,
    version       bigint       not null default 0,
    unique (operateur_id, debut)
);

-- Lignes de stock initial (RG-DEC-07) : mêmes règles qu'une ligne de DSM. Compte d'âge sous forme
-- canonique ('00', '0' … '19', '20+'). Dénomination normalisée stockée pour l'unicité (RG-DEC-11).
create table declarations.ligne_stock_initial (
    point_de_depart_id       bigint         not null references declarations.point_de_depart (id) on delete cascade,
    rang                     integer        not null,
    cle                      text           not null check (cle in ('MB', 'MV', 'NB', 'NV')),
    millesime                integer,
    denomination             text,
    denomination_normalisee  text,
    compte                   text           not null,
    volume                   numeric(12, 2) not null check (volume >= 0),
    primary key (point_de_depart_id, rang),
    check ((cle in ('MB', 'MV')) = (millesime is not null and denomination is null))
);

-- Agrégat DeclarationStocksMouvements (spec 05 §3.2). Ni chevauchement (une DSM par opérateur et début)
-- ni plus d'une DSM non validée par opérateur (RG-DEC-04, 05). Ni montant de cotisation ni état de
-- facturation (analyse §3).
create table declarations.dsm (
    id               bigint       generated by default as identity primary key,
    operateur_id     bigint       not null references operateurs.operateur (id),
    type             text         not null check (type in ('PRODUCTEUR', 'NEGOCIANT')),
    debut            date         not null,
    fin              date         not null,
    etat             text         not null check (etat in ('BROUILLON', 'ENVOYEE', 'EN_INSTRUCTION',
                         'COMPLEMENTS_DEMANDES', 'COMPLEMENTS_RECUS', 'VALIDEE')),
    date_dia         date,
    envoyee_le       timestamptz,
    validee_le       timestamptz,
    validee_par_id   bigint,
    nom_validee_par  text,
    version          bigint       not null default 0,
    unique (operateur_id, debut)
);
create unique index dsm_une_non_validee on declarations.dsm (operateur_id) where etat <> 'VALIDEE';

-- Lignes de DSM en table large (A-DEC-6) : une colonne par colonne de la DSM, c01 à c25, en litres
-- d'alcool pur ; la colonne 26 (stock de fin) est calculée, jamais stockée (RG-DEC-17). L'identifiant
-- est tiré de la séquence avant l'enregistrement et réinséré tel quel : il reste stable d'un
-- enregistrement à l'autre (commentaires et justificatifs y renverront, lots 2 et 3).
create table declarations.ligne_dsm (
    id                       bigint         generated by default as identity primary key,
    dsm_id                   bigint         not null references declarations.dsm (id) on delete cascade,
    rang                     integer        not null,
    cle                      text           not null check (cle in ('MB', 'MV', 'NB', 'NV')),
    millesime                integer,
    denomination             text,
    denomination_normalisee  text,
    compte                   text           not null,
    origine                  text           not null check (origine in ('REPRISE', 'AJOUT')),
    c01 numeric(12, 2) not null default 0, c02 numeric(12, 2) not null default 0,
    c03 numeric(12, 2) not null default 0, c04 numeric(12, 2) not null default 0,
    c05 numeric(12, 2) not null default 0, c06 numeric(12, 2) not null default 0,
    c07 numeric(12, 2) not null default 0, c08 numeric(12, 2) not null default 0,
    c09 numeric(12, 2) not null default 0, c10 numeric(12, 2) not null default 0,
    c11 numeric(12, 2) not null default 0, c12 numeric(12, 2) not null default 0,
    c13 numeric(12, 2) not null default 0, c14 numeric(12, 2) not null default 0,
    c15 numeric(12, 2) not null default 0, c16 numeric(12, 2) not null default 0,
    c17 numeric(12, 2) not null default 0, c18 numeric(12, 2) not null default 0,
    c19 numeric(12, 2) not null default 0, c20 numeric(12, 2) not null default 0,
    c21 numeric(12, 2) not null default 0, c22 numeric(12, 2) not null default 0,
    c23 numeric(12, 2) not null default 0, c24 numeric(12, 2) not null default 0,
    c25 numeric(12, 2) not null default 0,
    unique (dsm_id, rang),
    check ((cle in ('MB', 'MV')) = (millesime is not null and denomination is null))
);
create index ligne_dsm_dsm on declarations.ligne_dsm (dsm_id);

-- Commentaires d'instruction (spec 05 §3.2.4, RG-DEC-24, 25), à part de la DSM : les écrire ne change pas sa
-- version. Ligne sans clé étrangère : les lignes sont réécrites à chaque enregistrement ; quand une ligne est
-- supprimée, le commentaire passe sur la DSM et garde son libellé (ligne_supprimee). Interne : côté BNIA
-- seulement ; motif : celui d'une demande de compléments, jamais interne.
create table declarations.commentaire (
    id               bigint       generated by default as identity primary key,
    dsm_id           bigint       not null references declarations.dsm (id) on delete cascade,
    ligne_id         bigint,
    ligne_supprimee  text,
    auteur_id        bigint       not null,
    nom_auteur       text         not null,
    cote             text         not null check (cote in ('BNIA', 'OPERATEUR')),
    ecrit_le         timestamptz  not null,
    modifie_le       timestamptz,
    texte            text         not null check (btrim(texte) <> ''),
    interne          boolean      not null default false,
    motif            boolean      not null default false,
    check (not interne or (cote = 'BNIA' and not motif))
);
create index commentaire_dsm on declarations.commentaire (dsm_id, ecrit_le);

-- Justificatifs (spec 05 §3.2.2, RG-DEC-26, 28), à part de la DSM comme les commentaires : un dépôt ne
-- change pas sa version. Ligne sans clé étrangère, ligne_supprimee comme pour les commentaires. Le
-- DocumentDepose (clé, nom, type, taille) est copié ici, sans jointure vers documents ; le document est
-- supprimé avec la référence, par le cas d'usage (ADR-018).
create table declarations.justificatif (
    id               bigint       generated by default as identity primary key,
    dsm_id           bigint       not null references declarations.dsm (id) on delete cascade,
    ligne_id         bigint,
    ligne_supprimee  text,
    type_mouvement   text         not null check (type_mouvement in ('ACHAT', 'AUTRES_FABRICATIONS',
                         'VENTE_NEGOCE', 'VENTE_EXPORT', 'REINTEGRATION')),
    type_piece       text         not null check (type_piece in ('FACTURE', 'DAE', 'AVOIR',
                         'DECLARATION_FABRICATION_DOUANES')),
    document_id      bigint       not null unique references documents.document (id),
    document_nom     text         not null,
    document_type    text         not null,
    document_taille  bigint       not null,
    reference        text,
    depose_par_id    bigint       not null,
    nom_depose_par   text         not null,
    depose_le        timestamptz  not null
);
create index justificatif_dsm on declarations.justificatif (dsm_id);

-- DRM d'un producteur (spec 05 §3.2.3, RG-DEC-27, 28) : un PDF par mois de la période, mois au 1er.
create table declarations.drm (
    id               bigint       generated by default as identity primary key,
    dsm_id           bigint       not null references declarations.dsm (id) on delete cascade,
    mois             date         not null check (extract(day from mois) = 1),
    document_id      bigint       not null unique references documents.document (id),
    document_nom     text         not null,
    document_type    text         not null,
    document_taille  bigint       not null,
    depose_par_id    bigint       not null,
    nom_depose_par   text         not null,
    depose_le        timestamptz  not null,
    unique (dsm_id, mois)
);

-- Grille des taux CVO (spec 05 §3.5, RG-DEC-30) : une seule grille, enregistrée d'un bloc. La fin d'un taux
-- n'est pas stockée : c'est la veille du début du suivant.
create table declarations.taux_cvo (
    debut                date          primary key,
    montant              numeric(8,2)  not null check (montant > 0),
    pourcentage_exonere  numeric(5,2)  not null check (pourcentage_exonere between 0 and 100)
);

-- Projection des factures des DSM (A-DEC-4, RG-DEC-34, révisée par la spec 08 §3.13) : le brouillon demandé
-- (retour de la demande de facture), puis la facture et les avoirs émis, reçus de facturation. piece : identifiant
-- de la pièce chez facturation, opaque, sans clé étrangère (A-FAC-8). Un document reçu deux fois n'est gardé
-- qu'une fois.
create table declarations.facture_dsm (
    id      bigint         generated by default as identity primary key,
    dsm_id  bigint         not null references declarations.dsm (id),
    piece   bigint         not null,
    type    text           not null check (type in ('BROUILLON', 'FACTURE', 'AVOIR')),
    numero  text,
    date    date,
    ht      numeric(12,2),
    tva     numeric(12,2),
    ttc     numeric(12,2),
    -- Un brouillon n'a ni numéro ni montant ; une pièce émise a tout.
    check ((type = 'BROUILLON') = (numero is null)),
    check (type = 'BROUILLON' or (date is not null and ht is not null and tva is not null and ttc is not null)),
    unique (type, numero),
    unique (piece, type)
);
create index facture_dsm_dsm on declarations.facture_dsm (dsm_id);

-- Journal des déclarations (RG-DEC-23, A-DEC-3), hors agrégat, en ajout seul, sans valeurs avant et
-- après. Acteur et DSM copiés, sans clé étrangère : l'entrée « brouillon supprimé » survit à la DSM
-- (RG-DEC-22). Vide pour une action sur le point de départ.
create table declarations.journal (
    id            bigint       generated by default as identity primary key,
    date          timestamptz  not null,
    acteur_id     bigint       not null,
    nom_acteur    text         not null,
    operateur_id  bigint       not null references operateurs.operateur (id) on delete cascade,
    dsm_id        bigint,
    periode       text,
    action        text         not null check (action in ('DSM_INITIEE', 'DSM_ENREGISTREE', 'DSM_IMPORTEE',
                      'DSM_ENVOYEE', 'DSM_PRISE_EN_INSTRUCTION', 'COMPLEMENTS_DEMANDES', 'DSM_VALIDEE', 'DSM_EDITEE',
                      'BROUILLON_SUPPRIME', 'JUSTIFICATIF_DEPOSE', 'JUSTIFICATIF_SUPPRIME', 'DRM_DEPOSEE',
                      'DRM_SUPPRIMEE', 'COMMENTAIRE_SUPPRIME', 'POINT_DE_DEPART_FIXE', 'POINT_DE_DEPART_MODIFIE',
                      'POINT_DE_DEPART_IMPORTE', 'FACTURATION_DEMANDEE', 'FACTURE_EMISE',
                      'FACTURATION_ABANDONNEE')),
    detail        text
);
create index journal_declarations_operateur on declarations.journal (operateur_id, date desc);
-- (dsm_id, date) : le journal d'une DSM, et sa dernière action (« modifiée le » du listing) lue dans l'index.
create index journal_declarations_dsm on declarations.journal (dsm_id, date desc);

-- Retards déjà signalés (RG-DEC-41, A-DEC-7, ADR-019) : une ligne par période en retard d'un opérateur.
-- DeclarationEnRetard n'est publié que si l'insertion réussit : une double exécution est inoffensive.
create table declarations.retard_signale (
    operateur_id  bigint       not null references operateurs.operateur (id) on delete cascade,
    debut         date         not null,
    signale_le    timestamptz  not null,
    primary key (operateur_id, debut)
);

-- =====================================================================================================
-- 6. facturation (spec 08) : lib en aval (ADR-021). Les sources lui demandent des factures ; elle en fait des
--    pièces légales, numérotées sans trou, figées à l'émission (RG-FAC-12, 14). Elle ne connaît aucune source :
